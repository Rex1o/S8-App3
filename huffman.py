from dataclasses import dataclass
from numpy.typing import NDArray
from sortedcontainers import SortedList
import numpy as np

# Huffman compressed file format:
#
# +-------------------+---------------------+----------------+-------------------+
# | Dictionary size   | Huffman dictionary  | Padding count  | Compressed data   |
# | 2 bytes (16 bits) | Variable size       | 1 byte         | Variable size     |
# +-------------------+---------------------+----------------+-------------------+

@dataclass(eq=False)
class Node:
    probability: float = 0
    symbol: int | None = None  # Value of the symbol is always a byte
    left: "Node | None" = None  # Zero
    right: "Node | None" = None  # One

    def is_leaf(self) -> bool:
        return self.left is None and self.right is None


class HuffmanTree:
    def __init__(self):
        self.root = None
        self.symbol_counts = None
        self.symbol_probabilities = None
        self.symbol_dict = dict()  # Symbol -> (code, bit length)

    # Create tree from data
    def create_tree_from_data(self, data: NDArray[np.uint8]):
        data = np.asarray(data, dtype=np.uint8).ravel()

        self.symbol_counts = np.bincount(data, minlength=256)
        self.symbol_dict.clear()

        if data.size == 0:
            self.symbol_probabilities = np.zeros(256)
            self.root = None
            return

        self.symbol_probabilities = self.symbol_counts / data.size
        sorted_probabilities = np.argsort(self.symbol_probabilities)

        sorted_nodes = SortedList(key=lambda node: node.probability)

        # Create all of the leaf nodes
        for index in sorted_probabilities:
            if self.symbol_probabilities[index] == 0.0:
                continue

            temp_node = Node(
                probability=float(self.symbol_probabilities[index]),
                symbol=int(index)
            )
            sorted_nodes.add(temp_node)

        # Combine the two nodes with the smallest probabilities
        while len(sorted_nodes) > 1:
            left_node = sorted_nodes.pop(0)
            right_node = sorted_nodes.pop(0)

            new_node = Node(
                probability=left_node.probability + right_node.probability,
                left=left_node,
                right=right_node
            )

            sorted_nodes.add(new_node)

        self.root = sorted_nodes[0]
        self.create_fast_lookup_dict()

    # Comments generated by chat gpt but verified
    # Serialize the Huffman tree using a preorder traversal (root, left, right).
    #
    # Each node is represented as:
    #   - Internal node: 0 (1 bit)
    #   - Leaf node:     1 (1 bit) followed by the symbol (8 bits)
    #
    # Example tree:
    #
    #           Root
    #          /    \
    #        A       *
    #               / \
    #              B   C
    #
    # A = 65 (01000001)
    # B = 66 (01000010)
    # C = 67 (01000011)
    #
    # Serialized bit sequence (preorder):
    #   Root     A          *     B          C
    #    0    1 01000001    0  1 01000010  1 01000011
    #
    # Combined:
    #   0101000010101000010101000011
    #
    # The bits are packed into bytes, starting from the most significant bit.
    # If the final byte is incomplete, zeros are appended as padding.
    #
    # No tree bit-length field is needed because the tree structure is
    # self-delimiting: every internal node has exactly two children.
    def binarize_dict(self) -> NDArray[np.uint8]:
        if self.root is None:
            return np.array([], dtype=np.uint8)

        output = bytearray()
        buffer = 0
        bit_count = 0

        # Simple function to write bits into a byte array buffer
        def write_bits(value: int, length: int):
            nonlocal buffer, bit_count

            buffer = (buffer << length) | value
            bit_count += length

            while bit_count >= 8:
                bit_count -= 8
                output.append((buffer >> bit_count) & 0xFF)
                buffer &= (1 << bit_count) - 1

        def traverse(node: Node):
            if node.is_leaf():
                # 1 = leaf, followed by its 8-bit symbol
                write_bits(1, 1)
                write_bits(int(node.symbol), 8)
            else:
                # 0 = internal node
                write_bits(0, 1)
                traverse(node.left)
                traverse(node.right)

        traverse(self.root)

        # Pad the final dictionary byte with zeros
        if bit_count > 0:
            output.append((buffer << (8 - bit_count)) & 0xFF)

        return np.frombuffer(bytes(output), dtype=np.uint8)

    # Comments generated by chat gpt but verified
    # Deserialize the Huffman tree from its packed byte representation.
    #
    # Read bits in the same preorder used during serialization:
    #   - Read 0: create an internal node, then recursively read its
    #             left subtree followed by its right subtree.
    #   - Read 1: read the next 8 bits as the symbol and create a leaf.
    #
    # Example serialized sequence:
    #   0 1 01000001 0 1 01000010 1 01000011
    #
    # Reconstruction:
    #   0 -> Root (internal node)
    #   1 -> A (leaf, symbol 65)
    #   0 -> Internal node (right child of Root)
    #   1 -> B (leaf, symbol 66)
    #   1 -> C (leaf, symbol 67)
    #
    # Result:
    #
    #           Root
    #          /    \
    #        A       *
    #               / \
    #              B   C
    #
    # The recursive traversal stops automatically once the complete
    # tree has been reconstructed. Remaining bits in the final byte
    # are padding and must be zero.
    #
    # The Huffman codes can then be reconstructed by traversing the tree:
    #   Left branch  = 0
    #   Right branch = 1
    #
    # In this example:
    #   A = 0
    #   B = 10
    #   C = 11
    def debinarize_dict(self, data: NDArray[np.uint8]):
        data = np.asarray(data, dtype=np.uint8).ravel()

        self.root = None
        self.symbol_dict.clear()

        if data.size == 0:
            return

        bit_position = 0
        total_bits = data.size * 8

        def read_bits(length: int) -> int:
            nonlocal bit_position

            if bit_position + length > total_bits:
                raise ValueError("Incomplete Huffman dictionary")

            value = 0

            for _ in range(length):
                byte_index = bit_position // 8
                bit_index = 7 - (bit_position % 8)

                bit = (int(data[byte_index]) >> bit_index) & 1
                value = (value << 1) | bit
                bit_position += 1

            return value

        def traverse() -> Node:
            is_leaf = read_bits(1)

            if is_leaf:
                symbol = read_bits(8)
                return Node(symbol=symbol)

            left = traverse()
            right = traverse()

            return Node(left=left, right=right)

        self.root = traverse()

        # Verify that remaining dictionary bits are only zero-padding
        if total_bits - bit_position >= 8:
            raise ValueError("Extra data in Huffman dictionary")

        while bit_position < total_bits:
            if read_bits(1) != 0:
                raise ValueError("Invalid Huffman dictionary padding")

        self.create_fast_lookup_dict()

    # Create a lookup dictionary from symbol to (code, length)
    def create_fast_lookup_dict(self):
        self.symbol_dict.clear()

        def traverse(node: Node, bits: int, length: int):
            if node.is_leaf():
                self.symbol_dict[node.symbol] = (bits, max(length, 1))
                return

            if node.left is not None:
                traverse(node.left, bits << 1, length + 1)

            if node.right is not None:
                traverse(node.right, (bits << 1) | 1, length + 1)

        if self.root is not None:
            traverse(self.root, 0, 0)

    # Compress data and prepend the Huffman dictionary
    def compress(self, data: NDArray[np.uint8]) -> NDArray[np.uint8]:
        data = np.asarray(data, dtype=np.uint8).ravel()

        self.create_tree_from_data(data)

        # Serialize Huffman dictionary
        dictionary = self.binarize_dict()

        # Encode input data
        output = bytearray()
        buffer = 0
        bit_count = 0

        for symbol in data:
            code, length = self.symbol_dict[int(symbol)]

            buffer = (buffer << length) | code
            bit_count += length

            while bit_count >= 8:
                bit_count -= 8
                output.append((buffer >> bit_count) & 0xFF)
                buffer &= (1 << bit_count) - 1

        # Number of padding bits in the last compressed byte
        padding = (8 - bit_count) % 8

        if bit_count > 0:
            output.append((buffer << padding) & 0xFF)

        # Header:
        # 2 bytes: dictionary size
        # N bytes: serialized Huffman dictionary
        # 1 byte: padding count
        header = bytearray()
        header.extend(dictionary.size.to_bytes(2, "big"))
        header.extend(dictionary.tobytes())
        header.append(padding)
        header.extend(output)

        return np.frombuffer(bytes(header), dtype=np.uint8)

    # Decompress data using the Huffman dictionary in the header
    def decompress(self, data: NDArray[np.uint8]) -> NDArray[np.uint8]:
        data = np.asarray(data, dtype=np.uint8).ravel()

        if data.size < 3:
            raise ValueError("Invalid compressed data")

        # Read dictionary size (16 bits)
        dictionary_size = int.from_bytes(data[:2].tobytes(), "big")

        dictionary_start = 2
        dictionary_end = dictionary_start + dictionary_size

        if data.size < dictionary_end + 1:
            raise ValueError("Incomplete compressed header")

        # Extract and reconstruct dictionary
        dictionary = data[dictionary_start:dictionary_end]
        self.debinarize_dict(dictionary)

        # Read padding count
        padding = int(data[dictionary_end])

        if padding > 7:
            raise ValueError("Invalid padding count")

        # Extract compressed payload
        compressed_data = data[dictionary_end + 1:]

        if compressed_data.size == 0 and padding != 0:
            raise ValueError("Padding without compressed data")

        total_valid_bits = compressed_data.size * 8 - padding

        if total_valid_bits < 0:
            raise ValueError("Invalid compressed bit count")

        # Empty input
        if self.root is None:
            if total_valid_bits != 0:
                raise ValueError("Missing Huffman dictionary")
            return np.array([], dtype=np.uint8)

        if total_valid_bits == 0:
            raise ValueError("Missing compressed payload")

        # Validate final padding bits
        if padding > 0:
            mask = (1 << padding) - 1
            if int(compressed_data[-1]) & mask:
                raise ValueError("Invalid compressed data padding")

        # Special case: tree contains only one symbol
        if self.root.is_leaf():
            # A single-symbol tree uses the one-bit code 0
            for byte in compressed_data:
                if int(byte) != 0:
                    raise ValueError("Invalid single-symbol payload")

            return np.full(
                total_valid_bits,
                self.root.symbol,
                dtype=np.uint8
            )

        # Decode the bitstream
        output = bytearray()
        current_node = self.root
        bits_read = 0

        for byte in compressed_data:
            for bit_index in range(7, -1, -1):
                if bits_read >= total_valid_bits:
                    break

                bit = (int(byte) >> bit_index) & 1
                bits_read += 1

                if bit == 0:
                    current_node = current_node.left
                else:
                    current_node = current_node.right

                if current_node is None:
                    raise ValueError("Invalid Huffman bitstream")

                if current_node.is_leaf():
                    output.append(current_node.symbol)
                    current_node = self.root

        # The final bit must end at a complete Huffman code
        if current_node is not self.root:
            raise ValueError("Incomplete Huffman code at end of stream")

        return np.frombuffer(bytes(output), dtype=np.uint8)

    # Visualize the Huffman tree
    def visualize_tree(self, filename="huffman_tree", view=True):
        from graphviz import Digraph

        if self.root is None:
            return

        dot = Digraph("Huffman Tree")
        dot.attr(rankdir="TB")

        def add_node(node):
            node_id = str(id(node))

            if node.is_leaf():
                dot.node(
                    node_id,
                    f"Symbol: {node.symbol}\nP: {node.probability:.4f}",
                    shape="box",
                    style="filled",
                    fillcolor="lightgreen"
                )
            else:
                dot.node(
                    node_id,
                    f"P: {node.probability:.4f}",
                    shape="circle"
                )

            if node.left is not None:
                add_node(node.left)
                dot.edge(node_id, str(id(node.left)), label="0")

            if node.right is not None:
                add_node(node.right)
                dot.edge(node_id, str(id(node.right)), label="1")

        add_node(self.root)

        dot.render(filename, format="svg", cleanup=True, view=view)


# External compression interface
def compress(data_to_compress: NDArray[np.uint8]) -> NDArray[np.uint8]:
    tree = HuffmanTree()
    return tree.compress(data_to_compress)


# External decompression interface
def decompress(data_to_uncompress: NDArray[np.uint8]) -> NDArray[np.uint8]:
    tree = HuffmanTree()
    return tree.decompress(data_to_uncompress)
